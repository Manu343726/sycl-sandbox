/// Procedural text texture: renders `text` in an 8×8 monospace bitmap
/// font.  (u, v) map onto a grid of glyph cells; UVs outside the text
/// area sample the background colour.  `v` grows upward (row 0 of the
/// font = top of the text), so text on a quad with its v-axis pointing
/// up reads upright.
struct Text {
    /// NUL-terminated string, max 63 visible characters.
    char text[64] = {};

    float3 color = {1, 1, 1};    ///< Glyph colour.
    float3 bg = {0, 0, 0};       ///< Background colour (outside glyphs).
    float cell_w = 0.2f;         ///< UV width of one glyph cell.
    float cell_h = 0.24f;        ///< UV height of one glyph cell.
    float origin_x = 0.f;        ///< UV x of the first glyph's left edge.
    float origin_y = 0.f;        ///< UV y of the first glyph row's bottom.

    Text() = default;

    /// Initialize with the text to render.
    explicit Text(const char *s) {
        set_text(s);
    }

    /// Copy the string into the fixed buffer (truncated to 63 chars).
    void set_text(const char *s) {
        for ( int i = 0; i < 63; i++ ) {
            char c = s ? s[i] : '\0';
            text[i] = c;
            if ( c == '\0' ) break;
        }
        text[63] = '\0';
    }

    /// Number of characters before the NUL terminator.
    int length() const {
        int n = 0;
        while ( n < 63 && text[n] != '\0' ) n++;
        return n;
    }

    /// Sample the text at (u, v); out-of-text UVs return the background.
    /// `time` and `rng` are ignored (deterministic texture).
    float3 sample(float u, float v, float time, RNG &rng) const {
        (void)time;
        (void)rng;

        // Glyph grid coordinates: which glyph column, which pixel row
        float gx = (u - origin_x) / cell_w;
        float gy = (v - origin_y) / cell_h;
        if ( gx < 0.f || gy < 0.f ) {
            return bg;
        }

        int col = (int)gx;
        int row_from_bottom = (int)gy;
        if ( col >= length() || row_from_bottom >= 8 ) {
            return bg;
        }

        // Pixel within the glyph cell (8×8)
        int px = (int)((gx - (float)col) * 8.f);
        int py = (int)((gy - (float)row_from_bottom) * 8.f);
        if ( px < 0 || px > 7 || py < 0 || py > 7 ) {
            return bg;
        }

        char c = text[col];
        if ( c < ' ' || c > '~' ) {
            return bg;
        }

        // Font rows are top-to-bottom, but v grows upward: invert.
        unsigned char bits = FONT8X8_BASIC[(int)(c - ' ')][7 - py];
        bool on = (bits & (0x80u >> px)) != 0;
        return on ? color : bg;
    }
};

