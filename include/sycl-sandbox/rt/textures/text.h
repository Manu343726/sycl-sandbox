/// @file
/// Procedural text texture.
///
/// Renders a fixed string in an embedded 8×8 monospace bitmap font
/// (classic public-domain `font8x8`, ASCII 32–126) onto any surface
/// UV-mapped quad/face.  The texture is initialized with the text
/// string; glyph colour, background colour, cell size, and origin are
/// configurable so the text can be placed and scaled freely in UV
/// space.
///
/// The font lives in a plain constexpr byte table (no external asset,
/// no dynamic allocation), so the texture stays a trivially copyable
/// POD that can be uploaded into device material arrays by value.

